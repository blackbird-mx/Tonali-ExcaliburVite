/**
 * Available animation types for Carta actors.
 */
export enum CartaAnimacion {
  /** Smooth floating/hovering in the air */
  Flotar = 'Flotar',
  /** Wobble side-to-side like being held loosely */
  Tambalear = 'Tambalear',
  /** Pulse/breathe scale effect */
  Pulsar = 'Pulsar',
  /** Spin card 360° */
  Girar = 'Girar',
  /** Bounce in from above */
  Rebotar = 'Rebotar',
  /** Slide in from off-screen */
  Deslizar = 'Deslizar',
  /** No idle animation */
  Ninguna = 'Ninguna',
}

